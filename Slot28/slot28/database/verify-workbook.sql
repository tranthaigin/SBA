USE LibraryDB;
GO

SELECT TOP (20) * FROM dbo.STUDENTS ORDER BY id DESC;
SELECT TOP (20) * FROM dbo.BOOKS ORDER BY id DESC;
SELECT TOP (20) * FROM dbo.STUDENTS_BOOKS ORDER BY student_id DESC, book_id DESC;
GO

SELECT
    (SELECT COUNT(*) FROM dbo.STUDENTS) AS StudentCount,
    (SELECT COUNT(*) FROM dbo.BOOKS) AS BookCount,
    (SELECT COUNT(*) FROM dbo.STUDENTS_BOOKS) AS StudentBookCount;
GO
